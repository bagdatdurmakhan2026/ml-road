import numpy as np

# 1. Наша матрица весов (например, 2 строки, 3 столбца)
matrix = np.array([[1, 2, 3],
                   [4, 5, 6]])

# 2. Вектор смещения (3 элемента — по одному на каждый столбец)
bias = np.array([10, 20, 30])

# 3. Бродкастинг в действии: добавляем вектор к матрице без циклов!
result = matrix + bias

print("Исходная матрица:\n", matrix)
print("Результат бродкастинга (матрица + вектор):\n", result)