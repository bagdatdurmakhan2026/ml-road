import numpy as np

# 1. Создаем матрицу 2х3 (2 строки, 3 столбца)
matrix = np.array([[1, 2, 3],
                   [4, 5, 6]])

print(f"Форма матрицы (shape): {matrix.shape}")

# 2. Сумма по всей матрице
print(f"Сумма всех элементов: {matrix.sum()}")

# 3. Сумма по осям (axis)
# axis=0 — складываем по вертикали (по строкам для каждого столбца)
print(f"Сумма по столбцам (axis=0): {matrix.sum(axis=0)}")

# axis=1 — складываем по горизонтали (по столбцам в каждой строке)
print(f"Сумма по строкам (axis=1): {matrix.sum(axis=1)}")