# Цель: Понять механику матричного умножения изнутри

def matrix_multiply(A, B):
    """
    Умножает матрицу A размерности (M x K) на матрицу B размерности (K x N).
    Возвращает матрицу результат размерности (M x N).
    """
    rows_a = len(A) # количество строк в A
    cols_a = len(A[0]) # количество столбцов в A
    rows_b = len(B) # количество строк в B
    cols_b = len(B[0]) # количество столбцов в B
    
    # Проверка на совместимость размеров матриц
    if cols_a != rows_b:
        raise ValueError(f'нельзя умножить матрицы: число столбцов первой ({cols_a}) != числу строк второй ({rows_b})!')
#     # Что делает ключевое слово raise: Оно намеренно «выбрасывает» (создает) исключение (ошибку), прерывая выполнение программы. Это лучше, чем если бы программа продолжила считать бред или тихо упала с непонятным сбоем.

# ValueError: Стандартный тип ошибки в Python, который сигнализирует, что передано значение правильного типа (числа), но с недопустимым содержимым для данной операции.
    
    # Инициализируем результирующую матрицу нулями (размер rows_a x cols_b)
    result = [[0.0 for _ in range(cols_b)] for _ in range(rows_a)]
    
    # Классический тройной цикл (сложность O(n^3))
    # i — строка матрицы A
    # j — столбец матрицы B
    # k — индекс для поэлементного перемножения и суммирования
    for i in range(rows_a):
#         Зачем нужен: Перебирает строки первой матрицы (A).

# Почему rows_a: Вспомни правило: размер результирующей матрицы берет количество строк от первой матрицы и количество столбцов от второй. Значит, в конечном результате будет столько же строк, сколько было в матрице A. Нам нужно пройти по каждой строке матрицы A, чтобы вычислить каждую строку результата.
        for j in range(cols_b):
#             Зачем нужен: Перебирает столбцы второй матрицы (B).

# Почему cols_b: Результирующая матрица берет ширину (количество столбцов) от матрицы B. Перебирая j, мы проходим по каждому столбцу матрицы B, чтобы заполнить ячейки в текущей строке результата.
            for k in range(cols_a): # можно также range(rows_b), так как cols_a == rows_b
                result[i][j] += A[i][k] * B[k][j]
                
    return result


