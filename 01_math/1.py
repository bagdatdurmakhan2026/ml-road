    # Тестовые матрицы
    # Матрица A: 2x3
    matrix_a = [
        [1, 2, 3,6 ],
        [4, 5, 6, 5]
    ]
    
    # Матрица B: 3x2
    matrix_b = [
        [7, 8],
        [9, 1],
        [2, 3],
        [1, 2]
    ]
    
    print("=== Умножение матриц на чистом Python ===")
    print("Матрица A:")
    for row in matrix_a:
        print(row)
        
    print("\nМатрица B:")
    for row in matrix_b:
        print(row)
        
    res = matrix_multiply(matrix_a, matrix_b)
    
    print("\nРезультат (A x B):")
    for row in res:
        print(row)